<?php
/**
 * Theme setup: supports, menus, image sizes, translations.
 *
 * @package SM_Marketplace
 */

defined( 'ABSPATH' ) || exit;

function sm_theme_setup() {
	load_theme_textdomain( 'sm-marketplace', SM_THEME_DIR . '/languages' );

	add_theme_support( 'title-tag' );
	add_theme_support( 'post-thumbnails' );
	add_theme_support( 'responsive-embeds' );
	add_theme_support( 'html5', array( 'search-form', 'comment-form', 'comment-list', 'gallery', 'caption', 'style', 'script', 'navigation-widgets' ) );
	add_theme_support(
		'custom-logo',
		array(
			'height'      => 64,
			'width'       => 240,
			'flex-height' => true,
			'flex-width'  => true,
		)
	);

	register_nav_menus(
		array(
			'primary'   => __( 'Primary menu (mega menu)', 'sm-marketplace' ),
			'footer'    => __( 'Footer menu', 'sm-marketplace' ),
			'utility'   => __( 'Top utility menu', 'sm-marketplace' ),
		)
	);

	// Image sizes used by listing cards and galleries (WebP generated by WordPress when the server supports it).
	add_image_size( 'sm-card', 640, 480, true );
	add_image_size( 'sm-gallery', 1280, 960, false );
	add_image_size( 'sm-thumb', 160, 120, true );
}
add_action( 'after_setup_theme', 'sm_theme_setup' );

/** Body classes for direction and language, used by CSS and tests. */
function sm_theme_body_class( $classes ) {
	$classes[] = 'sm-lang-' . sm_theme_current_language();
	$classes[] = 'sm-dir-' . sm_theme_dir();
	if ( sm_theme_is_home() ) {
		$classes[] = 'sm-is-home'; // Dark showcase header and footer (0.18.0).
	}
	if ( is_page_template( 'templates/dashboard.php' ) ) {
		$classes[] = 'sm-is-account'; // Light or dark account area (0.18.0).
	}
	return $classes;
}

/** True on the home page (front page or a page using the "SM — Home" template). */
function sm_theme_is_home() {
	return is_front_page() || is_page_template( 'templates/front-page-template.php' );
}
add_filter( 'body_class', 'sm_theme_body_class' );

/** Ensure <html dir> follows the selected language even without a core language pack. */
function sm_theme_language_attributes( $output ) {
	$lang = str_replace( '_', '-', get_locale() );
	return sprintf( 'lang="%s" dir="%s"', esc_attr( $lang ), esc_attr( sm_theme_dir() ) );
}
add_filter( 'language_attributes', 'sm_theme_language_attributes' );

/** hreflang alternates for each supported language. */
function sm_theme_hreflang() {
	$url = static function ( $code ) {
		if ( class_exists( 'SM\\Core\\I18n\\Language' ) ) {
			return SM\Core\I18n\Language::url_for( SM\Core\I18n\Language::current_unprefixed_url(), $code );
		}
		return sm_theme_language_url( $code );
	};
	foreach ( sm_theme_languages() as $code => $language ) {
		printf( '<link rel="alternate" hreflang="%s" href="%s">' . "\n", esc_attr( $code ), esc_url( $url( $code ) ) );
	}
	printf( '<link rel="alternate" hreflang="x-default" href="%s">' . "\n", esc_url( $url( sm_theme_default_language() ) ) );
}
add_action( 'wp_head', 'sm_theme_hreflang', 2 );

/** Lightweight front end: remove emoji scripts. */
remove_action( 'wp_head', 'print_emoji_detection_script', 7 );
remove_action( 'wp_print_styles', 'print_emoji_styles' );

/**
 * Account dark mode (0.18.0): the choice is kept in the browser and applied
 * before the page paints, so the account never flashes white.
 */
function sm_theme_account_theme_boot() {
	if ( ! is_page_template( 'templates/dashboard.php' ) ) {
		return;
	}
	echo "<script>try{var d=document.documentElement;if(localStorage.getItem('sm-theme')==='dark'){d.setAttribute('data-sm-theme','dark');}if(localStorage.getItem('sm-nav')==='mini'){d.setAttribute('data-sm-nav','mini');}}catch(e){}</script>\n";
}
add_action( 'wp_head', 'sm_theme_account_theme_boot', 1 );
