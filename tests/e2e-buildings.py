def kgm(fam, sec):
    return float(wp('$r = SM\\Core\\Modules::service("weight")->calculate(array("family"=>"%s","section"=>"%s","bars"=>1,"length"=>1000)); echo $r["total_kg"];' % (fam, sec)))
