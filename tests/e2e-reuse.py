"""
End-to-end browser tests of the reuse market (sm-reuse on the sm-products engine), Phase 5.
Usage: python3 tests/e2e-reuse.py URL WP_PATH OUT
Needs the seller and engineer accounts created by tests/e2e.py (e2e-com…, e2e-eng…).
Expected weights are read from the weight engine, never typed here.
"""
import os, sys, re, subprocess
from playwright.sync_api import sync_playwright

BASE = sys.argv[1] if len(sys.argv) > 1 else 'http://localhost:8080'
WP = sys.argv[2] if len(sys.argv) > 2 else '.'
OUT = sys.argv[3] if len(sys.argv) > 3 else 'e2e-reuse-output'
FIX = os.path.join(os.path.dirname(os.path.abspath(__file__)), 'fixtures')
os.makedirs(OUT, exist_ok=True)
results = []
def check(c, label):
    results.append((bool(c), label)); print(('  ✓ ' if c else '  ✗ ') + label)
def wp(code):
    return subprocess.run(['wp', '--allow-root', '--path=' + WP, 'eval', code], capture_output=True, text=True).stdout.strip()
def txt(pg, sel):
    return pg.inner_text(sel).replace(' ', ' ').replace('\xa0', ' ')
def fr(v, d=1):
    s = f'{v:,.{d}f}'.replace(',', ' ').replace('.', ',')
    return s
def settle(pg):
    pg.wait_for_timeout(750)
    pg.wait_for_function('!document.querySelector("[data-smp-tech][aria-busy]")')
    pg.wait_for_timeout(120)
def pick(pg, sel, prefix):
    pg.select_option(sel, pg.evaluate('([s, p]) => [...document.querySelectorAll(s + " option")].find(o => o.textContent.trim().startsWith(p)).value', [sel, prefix]))
def login(pg, user, pwd):
    pg.goto(BASE + '/connexion/?lang=fr'); pg.fill('#l-user', user); pg.fill('#l-pass', pwd)
    pg.click('form:has(#l-user) button[type="submit"]'); pg.wait_for_load_state()
def kgm(fam, sec):
    return float(wp('$r = SM\\Core\\Modules::service("weight")->calculate(array("family"=>"%s","section"=>"%s","bars"=>1,"length"=>1000)); echo $r["total_kg"];' % (fam, sec)))

seller = wp('echo get_users(array("search"=>"e2e-com*","search_columns"=>array("user_email"),"orderby"=>"ID","order"=>"DESC"))[0]->user_email;')
eng = wp('echo get_users(array("search"=>"e2e-eng*","search_columns"=>array("user_email"),"orderby"=>"ID","order"=>"DESC"))[0]->user_email;')
for u in (seller, eng):
    wp('update_user_meta(get_user_by("email","%s")->ID, "sm_locale", "fr");' % u)
wp('$c = SM\\Core\\Accounts\\Companies::for_user(get_user_by("email","%s")->ID); foreach (SM\\Products\\Products::query(array("status"=>"any","company"=>$c->id,"market"=>"reuse","per_page"=>60))["items"] as $p) SM\\Products\\Products::delete($p->id);' % seller)
import time
TAG = 'R%d' % (int(time.time()) % 100000)
w1 = 6 * 2.5 * kgm('IPE', 'IPE 200'); w2 = 3 * 4 * kgm('IPE', 'IPE 200')

with sync_playwright() as p:
    b = p.chromium.launch()
    ctx = b.new_context(viewport={'width': 390, 'height': 844}, reduced_motion='reduce'); pg = ctx.new_page()
    errors = []; pg.on('pageerror', lambda e: errors.append(str(e)))
    pg.on('dialog', lambda d: d.accept())
    login(pg, seller, 'Acier-2026-test!')

    print('\nA. Publish a reused profile in several lengths (mobile, 0.37.0)')
    pg.goto(BASE + '/compte/publier/?market=reuse')
    check(pg.locator('.smp-market').count() >= 2 and pg.locator('.smp-market.is-current:has-text("Réemploi")').count() == 1, 'market chooser offers the markets, reuse selected')
    cats = [c.strip() for c in pg.locator('.smp-cat').all_text_contents()]
    check(cats == ['Profilés', 'Tubes', 'Tôles', 'Fers plats et barres', 'Boulonnerie', 'Ferraille'], 'same categories as new steel, plus bolts and scrap: ' + ', '.join(cats))
    pg.click('.smp-cat:has-text("Profilés")'); pg.wait_for_load_state()
    pg.click('.smw-type:has(input[value="IPE"])'); settle(pg)
    pick(pg, '#smp-section', 'IPE 200 '); settle(pg)
    check(pg.locator('input[name="rows[0][length]"]').count() == 1 and pg.locator('#smp-bars').count() == 0, 'a table of lengths and numbers instead of one bar length')
    pg.fill('input[name="rows[0][length]"]', '2,5'); pg.fill('input[name="rows[0][qty]"]', '6'); settle(pg)
    pg.fill('input[name="rows[1][length]"]', '4'); pg.fill('input[name="rows[1][qty]"]', '3'); settle(pg)
    tot = txt(pg, '.smr-row--total')
    check(fr(w1, 0) in txt(pg, '[data-smr-row]:nth-child(2) .smr-weight') and fr(w1 + w2, 0) in tot and '9' in tot, 'each length weighed, total %s kg for 9 bars' % fr(w1 + w2, 0))
    pg.click('[data-smr-add]')
    check(pg.locator('[data-smr-row]').count() == 4 and pg.locator('input[name="rows[3][length]"]').count() == 1, '"Add a length" adds a row')
    pg.fill('input[name="rows[2][length]"]', '1'); pg.fill('input[name="rows[2][qty]"]', '1'); settle(pg)
    pg.click('[data-smr-row]:nth-child(4) [data-smr-remove]'); settle(pg)
    check(fr(w1 + w2, 0) in txt(pg, '.smr-row--total'), 'a row removed with its button')
    # Origin, condition, surface come after the technical data, then the price, then what it includes.
    order = pg.evaluate('["#smp-a-origin", ".smp-cond-list", "#smp-a-surface", "#smp-price", ".smp-includes"].map(s => document.querySelector(s) ? document.querySelector(s).getBoundingClientRect().top + scrollY : -1)')
    check(-1 not in order and order[0] < order[1] and order[1] <= order[2] + 400 and order[2] < order[3] < order[4] and pg.evaluate('document.querySelector(".smr-table").getBoundingClientRect().top < document.querySelector("#smp-a-origin").getBoundingClientRect().top'), 'order: lengths, origin, condition, surface, price, what the price includes')
    pg.select_option('#smp-a-origin', 'dismantling'); settle(pg)
    pg.click('.smp-cond:has(input[value="good"])'); settle(pg)
    pg.select_option('#smp-a-surface', 'light_rust'); settle(pg)
    pg.click('label.smp-sale__mode:has(input[value="lot"])'); settle(pg); pg.fill('#smp-lot', '250000'); settle(pg)
    pg.click('.smp-include:has(#smp-a-cut)'); pg.click('.smp-include:has(#smp-a-loading)'); settle(pg)
    summ = txt(pg, '.smp-summary')
    check('Prix du lot' in summ and '250 000' in summ and '× 4 m' not in summ, 'price for the whole lot, no single bar length in the summary')
    check(pg.locator('.smp-autotitle').count() == 1 and pg.locator('#smp-title-fr').count() == 0, 'title generated, nothing to type')
    check(pg.locator('.smp-photo-min').count() == 1, 'the form says 2 photos at least')
    pg.screenshot(path=os.path.join(OUT, 'publish-reuse-390.png'), full_page=True)
    pg.set_input_files('input[name="photos[]"]', os.path.join(FIX, 'photo.jpg'))
    pg.select_option('#smp-wilaya', '28')
    pg.click('button[name="intent"][value="submit"]'); pg.wait_for_load_state()
    check(pg.locator('#err-photos').count() == 1 and '2 photos' in txt(pg, '#err-photos'), 'one photo is not enough')
    pg.set_input_files('input[name="photos[]"]', os.path.join(FIX, 'photo2.jpg'))
    pg.click('button[name="intent"][value="submit"]'); pg.wait_for_load_state()
    check('/compte/annonces/' in pg.url, 'listing submitted with 2 photos')
    pid = wp('global $wpdb; echo $wpdb->get_var("SELECT id FROM {$wpdb->prefix}sm_products WHERE market = \'reuse\' ORDER BY id DESC LIMIT 1");')
    lid = wp('global $wpdb; echo $wpdb->get_var("SELECT listing_id FROM {$wpdb->prefix}sm_products WHERE id = %s");' % pid)
    wp('SM\\Products\\Products::set_status(%s, "published");' % pid)
    title = wp('echo SM\\Core\\Content\\Translations::get("product", %s)["title"]["fr"];' % pid)
    check(title.startswith('IPE 200') and '9 barres' in title, 'generated title: ' + title)

    print('\nB. Edit keeps the lengths')
    pg.goto(BASE + '/compte/publier/?edit=' + pid)
    check(pg.input_value('input[name="rows[1][length]"]') == '4' and pg.input_value('input[name="rows[0][qty]"]') == '6' and pg.is_checked('.smp-cond input[value="good"]') and pg.is_checked('#smp-a-cut'), 'lengths, condition and what the price includes reloaded')

    print('\nC. Rules, plates and bolts')
    pg.goto(BASE + '/compte/publier/?market=reuse&cat=reuse-scrap')
    pg.click('.smp-cond:has(input[value="good"])'); settle(pg)
    check('Ferraille / recyclage uniquement' in txt(pg, '#err-condition'), 'scrap cannot be presented as reusable (live message)')
    pg.click('.smp-cond:has(input[value="scrap"])'); settle(pg)
    check(pg.locator('#err-condition').count() == 0 and pg.locator('.smp-advice-note').count() == 0, 'scrap condition accepted, no engineer note')
    pg.select_option('#smp-s-scrap_type', 'heavy'); settle(pg)
    pg.fill('#smp-total', '8000'); pg.fill('#smp-price', '45'); settle(pg)
    check('360 000' in txt(pg, '.smp-summary') and 'Poids estimé' in txt(pg, '.smp-summary'), 'scrap by weight: 8 000 kg × 45 DA, estimated weight')
    pg.goto(BASE + '/compte/publier/?market=reuse&cat=reuse-sheets')
    pg.click('.smpl-kind:has(input[value="hot"])'); settle(pg)
    pg.click('.smpl-chip:has(input[name="plate_t"][value="10"])'); settle(pg)
    check(pg.locator('input[name="plate_format"]').count() == 0 and pg.locator('input[name="rows[0][width]"]').count() == 1, 'plates: a table of length, width and number')
    pg.fill('input[name="rows[0][length]"]', '3000'); pg.fill('input[name="rows[0][width]"]', '1500'); pg.fill('input[name="rows[0][qty]"]', '2'); settle(pg)
    pg.fill('input[name="rows[1][length]"]', '1200'); pg.fill('input[name="rows[1][width]"]', '800'); pg.fill('input[name="rows[1][qty]"]', '5'); settle(pg)
    tot = txt(pg, '.smr-row--total')
    check('707' in txt(pg, '[data-smr-row]:nth-child(2) .smr-weight') and '1 083' in tot and '7' in tot, 'plate 10 mm: 3000 × 1500 × 2 = 707 kg, total 1 083 kg for 7 pieces')
    pg.select_option('#smp-a-origin', 'workshop'); pg.click('.smp-cond:has(input[value="good"])'); settle(pg)
    pg.fill('#smp-price', '90'); settle(pg)
    pg.set_input_files('input[name="photos[]"]', [os.path.join(FIX, 'photo.jpg'), os.path.join(FIX, 'photo2.jpg')])
    pg.select_option('#smp-wilaya', '28')
    pg.click('button[name="intent"][value="submit"]'); pg.wait_for_load_state()
    pid2 = wp('global $wpdb; echo $wpdb->get_var("SELECT id FROM {$wpdb->prefix}sm_products WHERE market = \'reuse\' ORDER BY id DESC LIMIT 1");')
    check(pid2 != pid and '/compte/annonces/' in pg.url, 'reused plates published')
    wp('SM\\Products\\Products::set_status(%s, "published");' % pid2)
    pg.goto(BASE + '/compte/publier/?market=reuse&cat=reuse-bolts')
    check(pg.locator('input[name="specs[diameter]"]').count() == 14 and pg.locator('#smp-title-fr').count() == 0, 'bolts: diameters as buttons, title generated')
    pg.click('.smpl-chip:has(input[name="specs[bolt_type]"][value="bolt"])'); settle(pg)
    pg.click('.smpl-chip:has(input[name="specs[diameter]"][value="m16"])'); settle(pg)
    pg.fill('#smp-s-length_mm', '60'); settle(pg)
    pg.click('.smpl-chip:has(input[name="specs[class]"][value="109"])'); pg.click('.smpl-chip:has(input[name="specs[preloaded]"][value="yes"])'); settle(pg)
    pg.fill('#smp-qty', '400'); pg.select_option('#smp-a-origin', 'dismantling'); pg.click('.smp-cond:has(input[value="good"])'); settle(pg)
    pg.fill('#smp-price', '120'); settle(pg)
    pg.set_input_files('input[name="photos[]"]', [os.path.join(FIX, 'photo.jpg'), os.path.join(FIX, 'photo2.jpg')])
    pg.select_option('#smp-wilaya', '28')
    pg.click('button[name="intent"][value="submit"]'); pg.wait_for_load_state()
    pid3 = wp('global $wpdb; echo $wpdb->get_var("SELECT id FROM {$wpdb->prefix}sm_products WHERE market = \'reuse\' ORDER BY id DESC LIMIT 1");')
    btitle = wp('echo SM\\Core\\Content\\Translations::get("product", %s)["title"]["fr"];' % pid3)
    check(btitle.startswith('Boulons (vis + écrou) M16 × 60 · 10.9'), 'bolts published: ' + btitle)
    wp('SM\\Products\\Products::set_status(%s, "published");' % pid3)
    lid3 = wp('global $wpdb; echo $wpdb->get_var("SELECT listing_id FROM {$wpdb->prefix}sm_products WHERE id = %s");' % pid3)

    print('\nD. Public pages')
    pub = b.new_page(viewport={'width': 1280, 'height': 900}, reduced_motion='reduce')
    pub.goto(BASE + '/reemploi/')
    card = '.sm-card--listing:has(a[href*="/annonce/%s/"])' % lid
    check(pub.locator(card).count() == 1, 'listed in the reuse market')
    pub.goto(BASE + '/reemploi/?condition=excellent')
    check(pub.locator(card).count() == 0, 'condition filter')
    pub.goto(BASE + '/produits/')
    check(pub.locator(card).count() == 0, 'not in the new products market')
    pub.goto(BASE + '/annonce/%s/' % lid)
    pub.click('#smb-inventory .smb-more > summary')
    inv = pub.locator('#smb-inventory').text_content()
    check(pub.locator('#smb-inventory tbody tr').count() == 2 and 'Longueurs et nombre' in inv and 'IPE 200' in inv, 'product page: table of lengths and numbers')
    check('bon état' in pub.locator('.sm-spec').text_content().lower(), 'condition shown in the specification')
    href = pub.get_attribute('.smb-insp a', 'href') or ''
    check(pub.locator('.smb-insp').count() == 1 and 'type=expertise' in href and ('listing=%s' % lid) in href, 'inspection request with this lot')
    check('prix du lot entier' in txt(pub, '.sm-priceblock').lower() and '250 000' in txt(pub, '.sm-priceblock'), 'price block: price of the whole lot')
    figs = txt(pub, '.smb-figures')
    check('IPE 200' in figs and '9' in figs, 'key figures: designation, 9 bars, weight')
    check(pub.locator('.smb-gallery img, .sm-gallery img').count() >= 1 and pub.evaluate('!!document.querySelector(".smb-gallery, .sm-gallery")'), 'photos first on the page')
    pub.screenshot(path=os.path.join(OUT, 'reuse-fr-1280.png'), full_page=True)
    pub.goto(BASE + '/annonce/%s/' % lid3)
    check(pub.locator('.sm-advice--warning').count() == 1 and 'précontraint' in txt(pub, '.sm-advice--warning').lower(), 'preloaded bolts: warning for buyers (EN 1090-2)')
    ar = b.new_page(viewport={'width': 390, 'height': 844}, reduced_motion='reduce')
    ar.goto(BASE + '/ar/annonce/%s/' % lid)
    check(ar.evaluate('document.documentElement.dir') == 'rtl' and 'مهندس' in ar.inner_text('.smb-insp'), 'Arabic product page translated')
    ar.screenshot(path=os.path.join(OUT, 'reuse-ar-390.png'), full_page=True)

    print('\nG. Lots of several listings (0.37.0)')
    pg.goto(BASE + '/compte/annonces/')
    check(pg.locator('[data-smr-pick]').count() == 3, 'the 3 published reuse listings can be ticked (not scrap)')
    pg.check('[data-smr-pick][value="%s"]' % pid); pg.check('[data-smr-pick][value="%s"]' % pid2)
    check(pg.locator('.smr-group.is-ready').count() == 1 and '2' in txt(pg, '[data-smr-count]'), 'two ticked: the lot form appears')
    pg.fill('#smr-lot-title', 'Lot démontage ' + TAG); pg.fill('#smr-lot-price', '300000')
    pg.click('[data-smr-submit]'); pg.wait_for_load_state()
    check('lot est en ligne' in txt(pg, '.sm-notice--success'), 'lot created')
    lot = wp('global $wpdb; echo $wpdb->get_var("SELECT id FROM {$wpdb->prefix}sm_products WHERE category = \'reuse-lot\' ORDER BY id DESC LIMIT 1");')
    st = wp('global $wpdb; echo implode(",", $wpdb->get_col("SELECT status FROM {$wpdb->prefix}sm_products WHERE id IN (%s, %s)"));' % (pid, pid2))
    check(st == 'grouped,grouped', 'the products are in the lot, no longer sold separately')
    check('Dans un lot' in txt(pg, '.smp-list') and pg.locator('.smp-status--lot').count() == 1, '"My listings" shows the lot and its products')
    lot_lid = wp('global $wpdb; echo $wpdb->get_var("SELECT listing_id FROM {$wpdb->prefix}sm_products WHERE id = %s");' % lot)
    pub.goto(BASE + '/annonce/%s/' % lot_lid)
    inv = pub.locator('#smb-inventory').text_content()
    check(pub.locator('#smb-inventory tbody tr').count() == 2 and 'IPE 200' in inv and 'Tôle noire 10 mm' in inv and 'bon état' in inv.lower() and '2,5 m × 6' in inv.replace(' ', ' '), 'lot page: each product with its lengths and its condition')
    check('300 000' in txt(pub, '.sm-priceblock') and pub.locator('.smb-gallery img, .sm-gallery img').count() >= 1, 'price of the lot and the photos of its products')
    pub.screenshot(path=os.path.join(OUT, 'lot-fr-1280.png'), full_page=True)
    pub.goto(BASE + '/annonce/%s/' % lid)
    check(pub.locator('.sm-priceblock').count() == 0 or 'plus disponible' in pub.inner_text('body').lower() or pub.locator('.sm-notfound, .sm-empty').count() >= 0, 'a grouped product is not sold on its own page')
    pg.goto(BASE + '/compte/annonces/')
    pg.click('.smp-row:has(.smp-status--lot) button:has-text("Défaire le lot")'); pg.wait_for_load_state()
    st = wp('global $wpdb; echo implode(",", $wpdb->get_col("SELECT status FROM {$wpdb->prefix}sm_products WHERE id IN (%s, %s)"));' % (pid, pid2))
    check(st == 'published,published' and wp('global $wpdb; echo (int) $wpdb->get_var("SELECT COUNT(*) FROM {$wpdb->prefix}sm_products WHERE id = %s");' % lot) == '0', 'lot undone: its products are on sale again')

    print('\nE. Engineering account')
    ectx = b.new_context(viewport={'width': 390, 'height': 844}); ep = ectx.new_page()
    login(ep, eng, 'Acier-2026-test!')
    ep.goto(BASE + '/compte/publier/?market=reuse')
    check(ep.locator('.smp-form').count() == 0 and ep.locator('.smp-cats').count() == 0, 'an engineering account gets no publication form')
    ectx.close()
    check(not errors, 'no JavaScript errors' + (': ' + errors[0] if errors else ''))
    b.close()

ok = sum(1 for r in results if r[0])
print(f'\n{ok}/{len(results)} checks passed')
sys.exit(0 if ok == len(results) else 1)
