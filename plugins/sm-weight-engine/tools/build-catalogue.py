"""Builds data/sections.php from the verified rows.

    cd tools/reference && EUROCODEPY_I=/path/i_profiles_euro.json python3 verify.py   # writes accepted.json
    python3 ../build-catalogue.py                                                     # writes ../../data/sections.php
Requires: shapely, numpy (pip install shapely numpy).
"""
import json, math, os
HERE = os.path.dirname(os.path.abspath(__file__))
REF = os.path.join(HERE, 'reference')
acc = json.load(open(os.path.join(REF, 'accepted.json')))
def num(x):
    x = float(x); return int(x) if x.is_integer() else round(x, 3)
def designation(fam, s):
    if fam in ('L', 'LI'):
        return 'L {:g}x{:g}x{:g}'.format(s['h'], s['b'], s['t'])
    if fam in ('HEA', 'HEB', 'HEM'):
        return fam + ' ' + s['designation'].split()[1]
    return s['designation']
fields = {'IPE': ['h', 'b', 'tw', 'tf', 'r'], 'HEA': ['h', 'b', 'tw', 'tf', 'r'], 'HEB': ['h', 'b', 'tw', 'tf', 'r'], 'HEM': ['h', 'b', 'tw', 'tf', 'r'],
          'IPN': ['h', 'b', 'tw', 'tf', 'r1', 'r2'], 'UPN': ['h', 'b', 'tw', 'tf', 'r1', 'r2'], 'UPE': ['h', 'b', 'tw', 'tf', 'r'], 'L': ['h', 'b', 't', 'r1', 'r2'], 'LI': ['h', 'b', 't', 'r1', 'r2']}
out = {}
for fam, keys in fields.items():
    rows = [[designation(fam, s), {k: num(s[k]) for k in keys}, round(s['A_calc'] * 100, 1), num(s['G'])] for s in acc[fam]]
    rows.sort(key=lambda r: (r[1]['h'], r[1]['b'], r[1].get('t', 0)))
    out[fam] = rows
def shs_area(B, H, t):
    ro = 2 * t if t <= 6 else (2.5 * t if t <= 10 else 3 * t); ri = ro - t
    return 2 * t * (B + H - 2 * t) - (4 - math.pi) * (ro * ro - ri * ri)
def sizes(name):
    for line in open(os.path.join(REF, 'raw', name)):
        if line.startswith('#') or not line.strip():
            continue
        a, ts = line.strip().split(':')
        for t in ts.split(','):
            yield float(a), float(t)
out['SHS'] = [['SHS {:g}x{:g}x{:g}'.format(B, B, T), {'h': num(B), 'b': num(B), 't': num(T)}, round(shs_area(B, B, T), 1), None] for B, T in sizes('shs_ferpinta_sizes.txt')]
out['CHS'] = [['CHS {:g}x{:g}'.format(D, T), {'d': num(D), 't': num(T)}, round(math.pi * T * (D - T), 1), None] for D, T in sizes('chs_ferpinta_sizes.txt')]
def php(v):
    if isinstance(v, dict):
        return 'array( ' + ', '.join(f"'{k}' => {php(x)}" for k, x in v.items()) + ' )'
    if isinstance(v, list):
        return 'array( ' + ', '.join(php(x) for x in v) + ' )'
    if v is None:
        return 'null'
    if isinstance(v, str):
        return "'" + v.replace("'", "\\'") + "'"
    return repr(v)
lines = ['<?php', '/**', ' * Reference rows of the steel section catalogue (generated by tools/build-catalogue.py — do not edit by hand).', ' *',
         ' * family => list of [ designation, dimensions (mm), area (mm2, computed from the dimensions), published mass (kg/m) or null ].',
         ' * Every rolled-section row was cross-checked before inclusion (see docs/VERIFICATION.md).', ' *', ' * @package SM\\WeightEngine', ' */', '',
         "defined( 'ABSPATH' ) || exit;", '', 'return array(']
for fam, rows in out.items():
    lines.append(f"\t'{fam}' => array(")
    lines += ['\t\t' + php(r) + ',' for r in rows]
    lines.append('\t),')
lines.append(');')
open(os.path.join(HERE, '..', 'data', 'sections.php'), 'w').write('\n'.join(lines) + '\n')
print({k: len(v) for k, v in out.items()})
